  let lang = 'de';
  function t(key, vars) {
    let s = (STR[lang] && STR[lang][key]) || STR.de[key] || key;
    if (vars) for (const k of Object.keys(vars)) s = s.replace('{' + k + '}', vars[k]);
    return s;
  }
  function setLang(l) {
    lang = STR[l] ? l : 'en';
    document.documentElement.lang = lang;
    applyDom(document);
  }
  function applyDom(rootEl) {
    rootEl.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
    rootEl.querySelectorAll('[data-i18n-ph]').forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  }
